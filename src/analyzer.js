import fs from "node:fs";
import path from "node:path";
import { findServices, isMicroservices } from "./services.js";
import { detectCloud } from "./cloud.js";

const read = (p) => { try { return fs.readFileSync(p, "utf8"); } catch { return null; } };
const exists = (cwd, f) => fs.existsSync(path.join(cwd, f));

const DEP_MAP = {
  frontend: { react: "React", next: "Next.js", vue: "Vue", svelte: "Svelte", "@angular/core": "Angular", tailwindcss: "Tailwind CSS" },
  backend:  { express: "Express", fastify: "Fastify", "@nestjs/core": "NestJS", koa: "Koa" },
  database: { mongoose: "MongoDB (Mongoose)", mongodb: "MongoDB", pg: "PostgreSQL", mysql2: "MySQL", prisma: "Prisma", "@prisma/client": "Prisma", sequelize: "Sequelize", redis: "Redis", ioredis: "Redis" },
  auth:     { jsonwebtoken: "JWT", passport: "Passport", bcrypt: "bcrypt", bcryptjs: "bcrypt", "next-auth": "NextAuth" },
  testing:  { jest: "Jest", vitest: "Vitest", mocha: "Mocha", supertest: "Supertest", cypress: "Cypress", "@playwright/test": "Playwright" }
};

export function analyze(cwd) {
  const info = { name: path.basename(cwd), languages: [], frontend: [], backend: [], database: [], auth: [], testing: [], scripts: {}, deploy: [], tree: [], services: [], microservices: false, cloud: [] };
  const pkgRaw = read(path.join(cwd, "package.json"));
  if (pkgRaw) {
    try {
      const pkg = JSON.parse(pkgRaw);
      info.name = pkg.name || info.name;
      info.languages.push(exists(cwd, "tsconfig.json") ? "TypeScript" : "JavaScript");
      info.scripts = pkg.scripts || {};
      const deps = { ...pkg.dependencies, ...pkg.devDependencies };
      for (const [cat, map] of Object.entries(DEP_MAP))
        for (const [dep, label] of Object.entries(map))
          if (deps[dep] && !info[cat].includes(label)) info[cat].push(label);
    } catch { /* invalid package.json: ignore */ }
  }
  if (exists(cwd, "requirements.txt") || exists(cwd, "pyproject.toml")) {
    info.languages.push("Python");
    info.pyText = ((read(path.join(cwd, "requirements.txt")) || "") + (read(path.join(cwd, "pyproject.toml")) || "")).toLowerCase();
    for (const [d, l] of [["django", "Django"], ["flask", "Flask"], ["fastapi", "FastAPI"]]) if (info.pyText.includes(d)) info.backend.push(l);
    for (const [d, l] of [["pytest", "pytest"]]) if (info.pyText.includes(d) || exists(cwd, "tests")) info.testing.push(l);
  }
  if (exists(cwd, "pubspec.yaml")) {
    info.languages.push("Dart"); info.frontend.push("Flutter");
    const pub = read(path.join(cwd, "pubspec.yaml")) || "";
    for (const [k, l] of [["flutter_bloc", "BLoC"], ["provider", "Provider"], ["riverpod", "Riverpod"], ["mobx", "MobX"]]) if (pub.includes(k)) info.frontend.push(l);
  }
  if (exists(cwd, "go.mod")) { info.languages.push("Go"); info.testing.push("go test"); }
  if (exists(cwd, "Dockerfile") || exists(cwd, "docker-compose.yml")) info.deploy.push("Docker");
  if (exists(cwd, ".github/workflows")) info.deploy.push("GitHub Actions");
  if (exists(cwd, "nginx.conf")) info.deploy.push("Nginx");
  info.services = findServices(cwd);
  info.microservices = isMicroservices(info.services);
  try { info.cloud = detectCloud(cwd).providers.map((p) => ({ aws: "AWS", azure: "Azure" }[p])); } catch { /* ignore */ }
  try {
    info.tree = fs.readdirSync(cwd, { withFileTypes: true })
      .filter((d) => !d.name.startsWith(".") && d.name !== "node_modules")
      .map((d) => d.name + (d.isDirectory() ? "/" : ""));
  } catch { /* ignore */ }
  return info;
}

// Choose gate commands from the scripts the project actually has.
export function detectGateCommands(info) {
  const s = info.scripts;
  const gate = [];
  if (s.test && !/no test specified/.test(s.test)) gate.push({ name: "Tests", cmd: "npm test --silent" });
  if (s.lint) gate.push({ name: "Lint", cmd: "npm run lint --silent" });
  if (s.typecheck) gate.push({ name: "Type Check", cmd: "npm run typecheck --silent" });
  else if (info.languages.includes("TypeScript")) gate.push({ name: "Type Check", cmd: "npx tsc --noEmit" });
  if (s.build) gate.push({ name: "Build", cmd: "npm run build --silent" });
  if (info.languages.includes("Python")) {
    if (info.testing.includes("pytest")) gate.push({ name: "Tests", cmd: "python -m pytest -q" });
    if ((info.pyText || "").includes("ruff")) gate.push({ name: "Lint", cmd: "ruff check ." });
  }
  if (info.languages.includes("Go")) { gate.push({ name: "Tests", cmd: "go test ./..." }); gate.push({ name: "Vet", cmd: "go vet ./..." }); }
  if (info.frontend.includes("Flutter")) { gate.push({ name: "Analyze", cmd: "flutter analyze" }); gate.push({ name: "Tests", cmd: "flutter test" }); }
  return gate;
}

export function renderContext(info) {
  const list = (a) => (a.length ? a.join(", ") : "not detected");
  return `# Project Context (auto-generated by agentforge)

Every agent MUST read this file before working. Update it when the stack changes.

| Item | Value |
|------|-------|
| Name | ${info.name} |
| Languages | ${list(info.languages)} |${info.language ? `\n| Language mode | ${info.language === "typescript" ? "TypeScript" : "JavaScript"} |` : ""}
| Frontend | ${list(info.frontend)} |
| Backend | ${list(info.backend)} |
| Database | ${list(info.database)} |
| Auth | ${list(info.auth)} |
| Testing | ${list(info.testing)} |
| Deployment | ${list(info.deploy)} |
| Cloud | ${list(info.cloud)} |

## Services (${info.microservices ? "multi-service system" : "single deployable"})
${info.services.length ? info.services.map((x) => `- \`${x.dir}\` (${x.kind})${x.needs.length ? " needs " + x.needs.join(", ") : ""}`).join("\n") : "- none detected"}

## npm scripts
${Object.keys(info.scripts).length ? Object.entries(info.scripts).map(([k, v]) => `- \`${k}\`: \`${v}\``).join("\n") : "- none"}

## Top-level layout
${info.tree.length ? info.tree.map((t) => `- ${t}`).join("\n") : "- empty project"}
`;
}
