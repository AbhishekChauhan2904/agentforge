import path from "node:path";
import { findServices } from "./services.js";
import { moduleGraph } from "./graph.js";
import { scanDb } from "./dbcheck.js";
import { walk, read, EXT, GENERATED, isTestFile, countLoc } from "./codefiles.js";

const T = { fanOutFile: 15, fanInFile: 20, godLoc: 400, godFanOut: 8, moduleCe: 6, sdpGap: 0.25 };
const noExt = (p) => p.replace(/\.(m?[jt]sx?|cjs|py|dart)$/, "").replace(/\/index$/, "");
const singular = (t) => t.replace(/ies$/, "y").replace(/s$/, "").replace(/(^|_)(\w)/g, (_, a, b) => b.toUpperCase());
const eid = (n) => String(n).replace(/[^A-Za-z0-9_]/g, "_").toUpperCase();

export function erDiagram(models) {
  const rel = [], ents = new Set(models.map((m) => m.name)), used = new Set();
  for (const m of models) for (const r of m.relations || []) {
    const to = r.to || models.find((x) => x.table === r.toTable)?.name || singular(r.toTable || "");
    if (!to) continue;
    ents.add(to); used.add(eid(m.name)); used.add(eid(to));
    rel.push(`  ${eid(m.name)} ${r.many ? "}o--o{" : "}o--||"} ${eid(to)} : "${r.field}"`);
  }
  if (!ents.size) return null;
  const lines = ["erDiagram", ...rel];
  for (const e of ents) if (!used.has(eid(e))) lines.push(`  ${eid(e)}`);
  return lines.join("\n");
}

export function scanDesign(cwd) {
  const findings = [], services = [];
  const add = (level, file, line, msg) => findings.push({ level, file, line, msg });
  for (const svc of findServices(cwd).filter((s) => s.kind !== "lib")) {
    const lang = svc.lang || "node", root = path.join(cwd, svc.dir), pre = (f) => path.join(svc.dir === "." ? "" : svc.dir, f);
    const g = moduleGraph(cwd, svc), names = Object.keys(g.nodes);
    if (names.length < 2) continue;
    const mods = names.map((n) => {
      const out = new Set(g.edges.filter((e) => e.from === n).map((e) => e.to)), inn = new Set(g.edges.filter((e) => e.to === n).map((e) => e.from));
      return { name: n, files: g.nodes[n], ca: inn.size, ce: out.size, instability: out.size + inn.size ? out.size / (out.size + inn.size) : 0 };
    }).sort((a, b) => a.instability - b.instability);
    const I = Object.fromEntries(mods.map((m) => [m.name, m.instability]));
    for (const m of mods) if (m.ce > T.moduleCe) add("warn", pre(m.name), 1, `module ${m.name} depends on ${m.ce} other modules (limit ${T.moduleCe}): it probably has too many responsibilities`);
    for (const e of g.edges) if (I[e.to] > I[e.from] + T.sdpGap) add("warn", pre(e.from), 1, `${e.from} (stability ${(1 - I[e.from]).toFixed(2)}) depends on less stable ${e.to} (${(1 - I[e.to]).toFixed(2)}): depend in the direction of stability, put an interface between them`);
    for (const c of g.cycles) add("error", pre(c[0]), 1, `circular dependency between ${c.join(", ")}: modules cannot be understood, tested or changed independently`);
    const files = walk(root, { flutter: lang === "flutter" }).filter((f) => EXT[lang].test(f) && !GENERATED.test(f) && !isTestFile(f));
    const fan = files.map((f) => ({ file: f, out: g.fileOut[f] || 0, in: g.fileIn[noExt(f.split(path.sep).join("/"))] || 0, loc: countLoc(read(path.join(root, f)), lang === "python" ? "python" : "c").code }));
    for (const f of fan) {
      if (f.loc > T.godLoc && f.out > T.godFanOut) add("warn", pre(f.file), 1, `god file: ${f.loc} lines and ${f.out} imports. It likely mixes several responsibilities (single-responsibility principle)`);
      else if (f.out > T.fanOutFile) add("warn", pre(f.file), 1, `imports ${f.out} other files (limit ${T.fanOutFile}): high fan-out makes this file fragile`);
      if (f.in > T.fanInFile) add("info", pre(f.file), 1, `imported by ${f.in} files: a change here has a wide blast radius; keep its interface small and stable`);
    }
    services.push({ name: svc.name, dir: svc.dir, modules: mods, topOut: [...fan].sort((a, b) => b.out - a.out).slice(0, 5).filter((f) => f.out), topIn: [...fan].sort((a, b) => b.in - a.in).slice(0, 5).filter((f) => f.in), cycles: g.cycles });
  }
  let models = []; try { models = scanDb(cwd).models; } catch { /* no data layer */ }
  return { services, findings, models, er: erDiagram(models) };
}

export function renderDesign({ services, findings, models, er }) {
  return `# Software Design Health (auto-generated by \`agentforge design\`)

Measured from the real import graph. **Stability** = how hard a module is to change (1 = many modules depend on it and it depends on little; 0 = it depends on everything). Good designs depend in the direction of stability: unstable code (routes, pages) depends on stable code (models, utils), never the reverse. Fan-in = files that import a file; fan-out = files it imports.

${services.map((s) => `## ${s.name} (${s.dir})

| Module | Files | Depended on by (Ca) | Depends on (Ce) | Stability |
|--------|-------|---------------------|-----------------|-----------|
${s.modules.map((m) => `| ${m.name} | ${m.files} | ${m.ca} | ${m.ce} | ${(1 - m.instability).toFixed(2)} |`).join("\n")}

Highest fan-out: ${s.topOut.map((f) => `\`${f.file}\` (${f.out})`).join(", ") || "none"}

Highest fan-in: ${s.topIn.map((f) => `\`${f.file}\` (${f.in})`).join(", ") || "none"}
`).join("\n") || "Not enough modules to analyse.\n"}
## Data model

${er ? `\`\`\`mermaid\n${er}\n\`\`\`\n\nModels found: ${models.map((m) => `${m.name} (${m.orm})`).join(", ")}.` : "No database models found."}

## Findings

${findings.length ? findings.map((f) => `- **${f.level}** \`${f.file}:${f.line}\` ${f.msg}`).join("\n") : "None."}
`;
}
