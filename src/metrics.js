import fs from "node:fs";
import path from "node:path";
import { findServices } from "./services.js";
import { walk, read, EXT, GENERATED, isTestFile, langOf, countLoc, functionsOf } from "./codefiles.js";

const DEFAULTS = { functionLines: 60, complexity: 15, nesting: 4, fileLines: 400 };
const limitsFrom = (cwd) => { try { return { ...DEFAULTS, ...(JSON.parse(read(path.join(cwd, ".ai/config.json"))).limits || {}) }; } catch { return { ...DEFAULTS }; } };

export function scanMetrics(cwd) {
  const L = limitsFrom(cwd), findings = [], services = [];
  const add = (level, file, line, msg) => findings.push({ level, file, line, msg });
  for (const svc of findServices(cwd).filter((s) => s.kind !== "lib" || EXT[s.lang || "node"])) {
    const lang = svc.lang || "node", root = path.join(cwd, svc.dir), pre = (f) => path.join(svc.dir === "." ? "" : svc.dir, f);
    const files = walk(root, { flutter: lang === "flutter" }).filter((f) => EXT[lang].test(f) && !GENERATED.test(f));
    const sum = { src: { files: 0, code: 0, comment: 0, blank: 0 }, test: { files: 0, code: 0, comment: 0, blank: 0 } }, byLang = {}, big = [], fns = [];
    for (const f of files) {
      const text = read(path.join(root, f)); if (!text) continue;
      const loc = countLoc(text, lang === "python" ? "python" : "c"), kind = isTestFile(f) ? "test" : "src";
      for (const k of ["files", "code", "comment", "blank"]) sum[kind][k] += k === "files" ? 1 : loc[k];
      const l = langOf(f); if (l && kind === "src") byLang[l] = (byLang[l] || 0) + loc.code;
      if (kind !== "src") continue;
      big.push({ file: pre(f), code: loc.code });
      if (loc.code > L.fileLines) add("warn", pre(f), 1, `${loc.code} lines of code (limit ${L.fileLines}): split this file by responsibility`);
      for (const fn of functionsOf(text, lang)) {
        fns.push({ ...fn, file: pre(f) });
        const where = `function ${fn.name}`;
        if (fn.lines > L.functionLines * 2.5) add("error", pre(f), fn.line, `${where} is ${fn.lines} lines long (limit ${L.functionLines}, hard limit ${L.functionLines * 2.5}): break it into smaller functions`);
        else if (fn.lines > L.functionLines) add("warn", pre(f), fn.line, `${where} is ${fn.lines} lines long (limit ${L.functionLines})`);
        if (fn.complexity > L.complexity * 2) add("error", pre(f), fn.line, `${where} has cyclomatic complexity ${fn.complexity} (limit ${L.complexity}, hard limit ${L.complexity * 2}): too many branches to test and reason about`);
        else if (fn.complexity > L.complexity) add("warn", pre(f), fn.line, `${where} has cyclomatic complexity ${fn.complexity} (limit ${L.complexity})`);
        if (fn.depth > L.nesting) add("warn", pre(f), fn.line, `${where} nests ${fn.depth} levels deep (limit ${L.nesting}): use early returns or extract helpers`);
      }
    }
    if (sum.src.code > 500 && sum.test.code / sum.src.code < 0.15) add("info", pre("."), 1, `only ${Math.round((sum.test.code / sum.src.code) * 100)} lines of test code per 100 lines of source in ${svc.name}`);
    services.push({ name: svc.name, dir: svc.dir, lang, ...sum, ratio: sum.src.code ? sum.test.code / sum.src.code : 0, byLang,
      largest: big.sort((a, b) => b.code - a.code).slice(0, 5), complex: [...fns].sort((a, b) => b.complexity - a.complexity).slice(0, 5), functions: fns.length });
  }
  return { services: services.filter((s) => s.src.files + s.test.files > 0), findings, limits: L };
}

export function renderMetrics({ services, findings, limits }) {
  const tot = services.reduce((a, s) => ({ files: a.files + s.src.files, code: a.code + s.src.code, test: a.test + s.test.code }), { files: 0, code: 0, test: 0 });
  return `# Code Metrics (auto-generated by \`agentforge metrics\`)

Lines of code exclude blank lines and comments. Complexity is the approximate cyclomatic complexity (1 + branches). Function-level metrics cover JavaScript, TypeScript and Python; Dart is measured per file. Limits: function ${limits.functionLines} lines, complexity ${limits.complexity}, nesting ${limits.nesting}, file ${limits.fileLines} lines (errors at 2.5x lines / 2x complexity). Change them with \`"limits"\` in \`.ai/config.json\`.

**Total:** ${tot.files} source files, ${tot.code} lines of code, ${tot.test} lines of tests.

| Service | Source files | Source LOC | Test LOC | Tests per 100 src LOC | Comments | Functions |
|---------|--------------|-----------|----------|-----------------------|----------|-----------|
${services.map((s) => `| ${s.name} (${s.dir}) | ${s.src.files} | ${s.src.code} | ${s.test.code} | ${Math.round(s.ratio * 100)} | ${s.src.code + s.src.comment ? Math.round((s.src.comment / (s.src.code + s.src.comment)) * 100) : 0}% | ${s.functions} |`).join("\n") || "| - | | | | | | |"}

${services.map((s) => `## ${s.name} (${s.dir})

By language (source LOC): ${Object.entries(s.byLang).sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} ${n}`).join(", ") || "none"}

Largest files: ${s.largest.map((f) => `\`${f.file}\` (${f.code})`).join(", ") || "none"}

Most complex functions: ${s.complex.map((f) => `\`${f.name}\` ${f.file}:${f.line} (complexity ${f.complexity}, ${f.lines} lines, depth ${f.depth})`).join("; ") || "none"}
`).join("\n")}
## Findings

${findings.length ? findings.map((f) => `- **${f.level}** \`${f.file}:${f.line}\` ${f.msg}`).join("\n") : "None."}
`;
}
